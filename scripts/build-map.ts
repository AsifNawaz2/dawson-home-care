/**
 * npm run map — builds content/map/lowcountry.ts (SPEC_FEATURES §6.2). Run once; commit the output.
 *
 * Source: us-atlas `counties-10m.json` (U.S. Census Bureau cartographic boundaries, public
 * domain), the best source reachable from the build container. It's generalised (Beaufort County
 * is a single shape — no separate islands or creeks), so coastlines are smoothed into a drawn,
 * illustrative style. For a detailed coastline, pass a TopoJSON built from the 1:500k Census
 * county file (cb_*_us_county_500k) with an object named `counties`:
 *
 *   npm run map -- path/to/counties-500k.topo.json
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { feature, merge, mesh } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";
import type { MultiPolygon, Polygon } from "geojson";
import { BBOX, VIEW_H, VIEW_W, project } from "../lib/projection";

const require = createRequire(import.meta.url);
const src = process.argv[2] ?? require.resolve("us-atlas/counties-10m.json");
/** The generalised default isn't drawn on the site (it puts Hilton Head inland). */
const detailed = Boolean(process.argv[2]);
const topo = JSON.parse(readFileSync(src, "utf8")) as Topology<{
  counties: GeometryCollection<{ name: string }>;
}>;

// Counties that touch the map box (with a margin so the land runs off every edge).
const PAD = 0.15;
const all = feature(topo, topo.objects.counties).features;
const keep = new Set(
  all
    .filter((f) => {
      const g = f.geometry as Polygon | MultiPolygon;
      const coords = (
        g.type === "Polygon" ? g.coordinates.flat() : g.coordinates.flat(2)
      ) as number[][];
      return coords.some(
        ([lng, lat]) =>
          lng! > BBOX.west - PAD &&
          lng! < BBOX.east + PAD &&
          lat! > BBOX.south - PAD &&
          lat! < BBOX.north + PAD,
      );
    })
    .map((f) => String(f.id)),
);
const geoms = topo.objects.counties.geometries.filter((g) => keep.has(String(g.id)));
const collection = { ...topo.objects.counties, geometries: geoms };

const r1 = (n: number) => Math.round(n * 10) / 10;
const pt = ([lng, lat]: number[]) => project(lng!, lat!).map(r1) as [number, number];

/** Smooth closed ring: quadratic curves through edge midpoints (keeps the shape, softens steps). */
function smoothRing(ring: number[][]) {
  const p = ring.slice(0, -1).map(pt);
  if (p.length < 3) return "";
  const mid = (a: number[], b: number[]) => [r1((a[0]! + b[0]!) / 2), r1((a[1]! + b[1]!) / 2)];
  const m0 = mid(p[p.length - 1]!, p[0]!);
  let d = `M${m0[0]} ${m0[1]}`;
  for (let i = 0; i < p.length; i++) {
    const c = p[i]!;
    const m = mid(c, p[(i + 1) % p.length]!);
    d += `Q${c[0]} ${c[1]} ${m[0]} ${m[1]}`;
  }
  return d + "Z";
}
function smoothLine(line: number[][]) {
  const p = line.map(pt);
  if (p.length < 2) return "";
  let d = `M${p[0]![0]} ${p[0]![1]}`;
  for (let i = 1; i < p.length - 1; i++) {
    const c = p[i]!;
    const n = p[i + 1]!;
    d += `Q${c[0]} ${c[1]} ${r1((c[0] + n[0]) / 2)} ${r1((c[1] + n[1]) / 2)}`;
  }
  const last = p[p.length - 1]!;
  return d + `L${last[0]} ${last[1]}`;
}

const land = merge(topo, geoms as never) as MultiPolygon;
const landPath = land.coordinates.map((poly) => poly.map(smoothRing).join("")).join("");
const borders = mesh(topo, collection as never, (a, b) => a !== b);
const countyPath = borders.coordinates.map(smoothLine).join("");

const out = `// Generated by scripts/build-map.ts from ${path.basename(src)} — do not edit by hand.
// Source: U.S. Census Bureau cartographic boundaries via us-atlas (public domain).
export const lowcountry = {
  /** false → the map stays schematic (towns + rings only). */
  detailed: ${detailed},
  viewBox: "0 0 ${VIEW_W} ${VIEW_H}",
  land: ${JSON.stringify(detailed ? landPath : "")},
  counties: ${JSON.stringify(detailed ? countyPath : "")},
} as const;
`;
mkdirSync("content/map", { recursive: true });
writeFileSync("content/map/lowcountry.ts", out);
console.log(
  `content/map/lowcountry.ts — ${geoms.length} counties, ${(out.length / 1024).toFixed(1)} KB`,
);
